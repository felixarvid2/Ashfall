/**
 * npm run balance:report [-- --out docs/balance-report.md --seed a --skip-plans] (D14): runs every sample build
 * and every bot plan and writes one markdown report.
 *  - Level 10: the bot's time to level 10 and deaths for every plan (scripts/sim/plans.ts).
 *  - Level 30 and the other sample builds (scripts/sim/builds.ts): DPS on a corrupted dummy, on a neutral dummy and
 *    against a pack of five (neutral, damage summed), all seeded, 60 s each.
 * The tables are deterministic for a seed, so a diff of the file shows what a balance change moved.
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { BUILDS } from './builds';
import { PLANS } from './plans';
import { playthrough } from './playthrough';
import { simulate, type Build } from './sim';

const arg = (name: string) => {
  const i = process.argv.indexOf(`--${name}`);
  return i >= 0 ? process.argv[i + 1] : undefined;
};
const out = resolve(arg('out') ?? 'docs/balance-report.md');
const seed = arg('seed') ?? 'a';
const skipPlans = process.argv.includes('--skip-plans');
const SECONDS = 60;
const NEUTRAL = 'security_trooper';

const clock = (s: number | undefined) => (s === undefined ? 'never' : `${Math.floor(s / 60)}:${String(Math.round(s % 60)).padStart(2, '0')}`);
const dps = (b: Build, dummy: string | undefined, pack?: number) => simulate(b, SECONDS, 'sim', { dummy, pack }).dps;
const n0 = (v: number) => Math.round(v).toLocaleString('en-US');

export interface BuildRow {
  name: string;
  level: number;
  classId: string;
  corrupted: number;
  neutral: number;
  pack: number;
}

export function buildRows(builds: readonly Build[] = BUILDS): BuildRow[] {
  return builds.map((b) => ({
    name: b.name,
    level: b.level,
    classId: b.classId ?? 'bastion',
    corrupted: dps(b, undefined),
    neutral: dps(b, NEUTRAL),
    pack: dps(b, NEUTRAL, 5),
  }));
}

/** The markdown tables, from measured rows. Exported so a test can check the layout without running the sims. */
export function renderReport(plans: { name: string; l10?: number; deaths: number }[], rows: BuildRow[], date: string): string {
  const lines: string[] = [];
  lines.push('# Balance report', '', `Generated by \`npm run balance:report\` on ${date} (seed \`${seed}\`). Do not edit by hand; run the script again.`, '');
  lines.push('## Level 10 (bot playthrough)', '', 'Time for the bot to reach level 10 and the deaths on the way. The band `npm run balance:check` enforces is 6:30 to 14:00 with at most 5 deaths.', '');
  lines.push('| Plan | Level 10 | Deaths |', '| --- | ---: | ---: |');
  if (plans.length === 0) lines.push('| (skipped) | | |');
  for (const p of plans) lines.push(`| ${p.name} | ${clock(p.l10)} | ${p.deaths} |`);
  lines.push('', '## Builds (damage per second)', '', `${SECONDS} s against a training dummy. Corrupted is a Lumen enemy (corrupted bonuses apply), neutral is a plain human, pack of 5 is five neutral dummies with their damage summed.`, '');
  lines.push('| Build | Class | Lv | Corrupted | Neutral | Pack of 5 | Pack / neutral |', '| --- | --- | ---: | ---: | ---: | ---: | ---: |');
  for (const r of rows) lines.push(`| ${r.name} | ${r.classId} | ${r.level} | ${n0(r.corrupted)} | ${n0(r.neutral)} | ${n0(r.pack)} | ${(r.pack / Math.max(1, r.neutral)).toFixed(2)}x |`);
  const l30 = rows.filter((r) => r.level >= 30);
  if (l30.length > 0) {
    lines.push('', '## Level 30 by class', '', '| Class | Best neutral | Best corrupted | Builds |', '| --- | ---: | ---: | ---: |');
    for (const id of [...new Set(l30.map((r) => r.classId))]) {
      const mine = l30.filter((r) => r.classId === id);
      lines.push(`| ${id} | ${n0(Math.max(...mine.map((r) => r.neutral)))} | ${n0(Math.max(...mine.map((r) => r.corrupted)))} | ${mine.length} |`);
    }
  }
  lines.push('');
  return lines.join('\n');
}

if (process.argv[1]?.endsWith('balanceReport.ts')) {
  const plans = skipPlans
    ? []
    : PLANS.map((plan) => {
        const r = playthrough(plan, { maxMinutes: 20, seed });
        console.log(`${plan.name}: L10 ${clock(r.levelTimes[10])}, ${r.deaths} deaths`);
        return { name: plan.name, l10: r.levelTimes[10], deaths: r.deaths };
      });
  const rows = buildRows();
  for (const r of rows) console.log(`${r.name}: ${n0(r.corrupted)} / ${n0(r.neutral)} / ${n0(r.pack)}`);
  mkdirSync(dirname(out), { recursive: true });
  writeFileSync(out, renderReport(plans, rows, new Date().toISOString().slice(0, 10)));
  console.log(`wrote ${out}`);
}
