/**
 * npm run balance:report [-- --out docs/balance-report.md --seed a --skip-plans] (D14): runs every sample build
 * and every bot plan and writes one markdown report.
 *  - Level 10: the bot's time to level 10 and deaths for every plan (scripts/sim/plans.ts).
 *  - Level 30 and the other sample builds (scripts/sim/builds.ts): DPS on a corrupted dummy, on a neutral dummy and
 *    against a pack of five (neutral, damage summed), all seeded, 60 s each.
 *  - Level 10 to 50 (B05, scripts/sim/stages.ts): the bot plays each later region's monsters at its levels, one plan
 *    per class, and the table has the time to the first and to the last level of the region and the deaths.
 *  - Survivability (B06): every build for 60 s against three attackers that hit back, dummy life unlimited: deaths,
 *    time below 30 % life, lowest life and damage taken.
 * The tables are deterministic for a seed, so a diff of the file shows what a balance change moved.
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { BUILDS } from './builds';
import { PLANS } from './plans';
import { playthrough, type PlayPlan } from './playthrough';
import { simulate, type Build, type Survival } from './sim';
import { STAGES, type PlayStage } from './stages';

const arg = (name: string) => {
  const i = process.argv.indexOf(`--${name}`);
  return i >= 0 ? process.argv[i + 1] : undefined;
};
const out = resolve(arg('out') ?? 'docs/balance-report.md');
const seed = arg('seed') ?? 'a';
const skipPlans = process.argv.includes('--skip-plans');
const skipStages = process.argv.includes('--skip-stages');
const SECONDS = 60;
const NEUTRAL = 'security_trooper';

const clock = (s: number | undefined) => {
  if (s === undefined) return 'never';
  const whole = Math.round(s);
  return `${Math.floor(whole / 60)}:${String(whole % 60).padStart(2, '0')}`;
};
const dps = (b: Build, dummy: string | undefined, pack?: number) => simulate(b, SECONDS, 'sim', { ...(dummy !== undefined && { dummy }), ...(pack !== undefined && { pack }) }).dps;
const n0 = (v: number) => Math.round(v).toLocaleString('en-US');

export interface BuildRow {
  name: string;
  level: number;
  classId: string;
  corrupted: number;
  neutral: number;
  pack: number;
  /** Fight-back run (B06); absent in rows made without it. */
  survival?: Survival;
}

/** One class's run through one region (B05). */
export interface StageRow {
  stage: string;
  plan: string;
  classId: string;
  from: number;
  to: number;
  reached: number;
  /** Seconds to the first level after the start, to start + 5 and to the end of the region (undefined: not reached). */
  first?: number;
  mid?: number;
  end?: number;
  deaths: number;
  avgLife: number;
}

/** A plan per class (the first listed) plays each region from its first level to its last. */
export function stageRows(stages: readonly PlayStage[] = STAGES, plans: readonly PlayPlan[] = PLANS, maxMinutes = 40): StageRow[] {
  const rows: StageRow[] = [];
  for (const stage of stages) {
    for (const classId of [...new Set(plans.map((p) => p.classId))]) {
      const plan = plans.find((p) => p.classId === classId)!;
      const from = stage.levels[0];
      const r = playthrough(plan, { stage, startLevel: from, maxMinutes, seed });
      const row: StageRow = { stage: stage.label, plan: plan.name, classId, from, to: stage.levels[1], reached: r.reached, deaths: r.deaths, avgLife: r.avgLife };
      const first = r.levelTimes[from + 1];
      const mid = r.levelTimes[from + 5];
      const end = r.levelTimes[stage.levels[1]];
      if (first !== undefined) row.first = first;
      if (mid !== undefined) row.mid = mid;
      if (end !== undefined) row.end = end;
      console.log(`${stage.label} / ${plan.name}: ${clock(end)} to ${stage.levels[1]}, ${r.deaths} deaths`);
      rows.push(row);
    }
  }
  return rows;
}

export function buildRows(builds: readonly Build[] = BUILDS): BuildRow[] {
  return builds.map((b) => ({
    name: b.name,
    level: b.level,
    classId: b.classId ?? 'bastion',
    corrupted: dps(b, undefined),
    neutral: dps(b, NEUTRAL),
    pack: dps(b, NEUTRAL, 5),
    survival: simulate(b, SECONDS, 'sim', { fightBack: true }).survival!,
  }));
}

/** The markdown tables, from measured rows. Exported so a test can check the layout without running the sims. */
export function renderReport(plans: { name: string; l10?: number; deaths: number }[], rows: BuildRow[], date: string, stages: readonly StageRow[] = []): string {
  const lines: string[] = [];
  lines.push('# Balance report', '', `Generated by \`npm run balance:report\` on ${date} (seed \`${seed}\`). Do not edit by hand; run the script again.`, '');
  lines.push('## Level 10 (bot playthrough)', '', 'Time for the bot to reach level 10 and the deaths on the way. The band `npm run balance:check` enforces is 6:30 to 14:00 with at most 5 deaths.', '');
  lines.push('| Plan | Level 10 | Deaths |', '| --- | ---: | ---: |');
  if (plans.length === 0) lines.push('| (skipped) | | |');
  for (const p of plans) lines.push(`| ${p.name} | ${clock(p.l10)} | ${p.deaths} |`);
  lines.push('', '## Builds (damage per second)', '', `${SECONDS} s against a training dummy. Corrupted is a Lumen enemy (corrupted bonuses apply), neutral is a plain human, pack of 5 is five neutral dummies with their damage summed.`, '');
  lines.push('| Build | Class | Lv | Corrupted | Neutral | Pack of 5 | Pack / neutral |', '| --- | --- | ---: | ---: | ---: | ---: | ---: |');
  for (const r of rows) lines.push(`| ${r.name} | ${r.classId} | ${r.level} | ${n0(r.corrupted)} | ${n0(r.neutral)} | ${n0(r.pack)} | ${(r.pack / Math.max(1, r.neutral)).toFixed(2)}x |`);
  const l30 = rows.filter((r) => r.level >= 30);
  if (l30.length > 0) {
    lines.push('', '## Level 30 by class', '', '| Class | Best neutral | Best corrupted | Builds |', '| --- | ---: | ---: | ---: |');
    for (const id of [...new Set(l30.map((r) => r.classId))]) {
      const mine = l30.filter((r) => r.classId === id);
      lines.push(`| ${id} | ${n0(Math.max(...mine.map((r) => r.neutral)))} | ${n0(Math.max(...mine.map((r) => r.corrupted)))} | ${mine.length} |`);
    }
  }
  if (stages.length > 0) {
    lines.push('', '## Level 10 to 50 (bot, one plan per class)', '', 'The bot starts each region at its first level with rare gear and one skill point per level, and fights that region\'s own monsters (the enemies of its packs, at its levels) in growing waves in the test arena. Times are game time to the first level after the start, to start + 5 and to the last level of the region ("never" = not reached in the time allowed).', '');
    for (const label of [...new Set(stages.map((s) => s.stage))]) {
      lines.push(`### ${label}`, '', '| Class | Plan | Reached | +1 | +5 | End | Deaths | Avg life |', '| --- | --- | ---: | ---: | ---: | ---: | ---: | ---: |');
      for (const s of stages.filter((x) => x.stage === label)) {
        lines.push(`| ${s.classId} | ${s.plan} | ${s.reached}/${s.to} | ${clock(s.first)} | ${clock(s.mid)} | ${clock(s.end)} | ${s.deaths} | ${Math.round(s.avgLife * 100)} % |`);
      }
      lines.push('');
    }
  }
  const fought = rows.filter((r) => r.survival);
  if (fought.length > 0) {
    lines.push('', '## Survivability (dummies that hit back)', '', `${SECONDS} s next to three Security Troopers of the build's level that attack (their life is unlimited, so the damage rows above still hold). The character wears rare gear in every slot, drinks a stim pack below 40 % life and respawns 3 s after dying. Time below 30 % counts only the time alive.`, '');
    lines.push('| Build | Class | Lv | Deaths | Time below 30 % | Lowest life | Damage taken / s |', '| --- | --- | ---: | ---: | ---: | ---: | ---: |');
    for (const r of fought) {
      const s = r.survival!;
      lines.push(`| ${r.name} | ${r.classId} | ${r.level} | ${s.deaths} | ${Math.round(s.below30 * 100)} % | ${Math.round(s.minLife * 100)} % | ${n0(s.takenPerSecond)} |`);
    }
  }
  lines.push('');
  return lines.join('\n');
}

if (process.argv[1]?.endsWith('balanceReport.ts')) {
  const plans = skipPlans
    ? []
    : PLANS.map((plan) => {
        const r = playthrough(plan, { maxMinutes: 20, seed });
        console.log(`${plan.name}: L10 ${clock(r.levelTimes[10])}, ${r.deaths} deaths`);
        return { name: plan.name, ...(r.levelTimes[10] !== undefined && { l10: r.levelTimes[10] }), deaths: r.deaths };
      });
  const rows = buildRows();
  const stages = skipStages ? [] : stageRows();
  for (const r of rows) console.log(`${r.name}: ${n0(r.corrupted)} / ${n0(r.neutral)} / ${n0(r.pack)}`);
  mkdirSync(dirname(out), { recursive: true });
  writeFileSync(out, renderReport(plans, rows, new Date().toISOString().slice(0, 10), stages));
  console.log(`wrote ${out}`);
}
